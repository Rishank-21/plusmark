  const text = readFileSync(p, "utf8");
  const have = JSON.parse(text);
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const add = Object.entries(S).filter(([k]) => !(k in have));
  if (add.length === 0) continue;
  const body = add.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v[idx])}`).join("," + eol);
  const end = text.lastIndexOf("}");
  const head = text.slice(0, end).replace(/\s+$/, "");
  writeFileSync(p, `${head},${eol}${body}${eol}}${text.slice(end + 1)}`);
  console.log(file, "added", add.length);
