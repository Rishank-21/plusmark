for (const [file, add] of [["en.json", en], ["hi.json", hi]]) {
  const p = dir + file;
  const text = readFileSync(p, "utf8");
  const have = JSON.parse(text);
  const lines = Object.entries(add).filter(([k]) => !(k in have)).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`);
  if (lines.length === 0) continue;
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const idx = text.lastIndexOf("}");
  const head = text.slice(0, idx).replace(/\s+$/, "");
  writeFileSync(p, head + "," + eol + lines.join("," + eol) + eol + "}" + text.slice(idx + 1));
  JSON.parse(readFileSync(p, "utf8"));
  console.log(file, "added", lines.length);
}
